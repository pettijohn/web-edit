import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["frontend/app.js"],
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2020"],
  outfile: "web_edit/static/app.js",
  legalComments: "external",
  metafile: true,
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
const licenses = ["Bundled frontend dependencies\n\nGenerated by npm run build.\n"];
for (const name of [...packages].sort()) {
  const pkg = JSON.parse(await readFile(`node_modules/${name}/package.json`, "utf8"));
  let license;
  for (const filename of ["LICENSE", "LICENSE.md", "LICENSE.txt"]) {
    try { license = await readFile(`node_modules/${name}/${filename}`, "utf8"); break; } catch (error) { if (error.code !== "ENOENT") throw error; }
  }
  if (!license) throw new Error(`License not found for ${name}`);
  licenses.push(`\n--- ${name}@${pkg.version} ---\n\n${license}`);
}
await writeFile("web_edit/static/THIRD_PARTY_LICENSES.txt", licenses.join("\n"));
console.log(`Bundled CodeMirror and ${packages.size} dependencies into web_edit/static/app.js`);
